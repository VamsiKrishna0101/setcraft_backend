import 'dotenv/config';
import fs from 'node:fs';
import path from 'node:path';
import { OpenAIContentClient, defaultAIModel } from "../utils/openai_client";
const root = path.resolve(__dirname, '..');
const file = path.join(root, 'data', 'fitness_ui.json');
const english: Record<string, string> = JSON.parse(fs.readFileSync(path.join(root, 'data', 'fitness_ui.en.json'), 'utf8'));
const reviewed: Record<string, Record<string,string>> = JSON.parse(fs.readFileSync(path.join(root, 'data', 'fitness_ui.reviewed.json'), 'utf8'));
const data: Record<string, Record<string,string>> = fs.existsSync(file) ? JSON.parse(fs.readFileSync(file, 'utf8')) : {};
data.en = english;
const ai = new OpenAIContentClient({ timeoutMs: 120000, reasoningEffort: "low" });
const model = process.env.OPENAI_TRANSLATION_MODEL || process.env.OPENAI_PHYSIQUE_MODEL || defaultAIModel();
const locales = ['de', 'fr', 'sv', 'no', 'da', 'nl', 'es', 'it'];
const localeNames: Record<string, string> = { de: 'German', fr: 'French', sv: 'Swedish', no: 'Norwegian Bokmål', da: 'Danish', nl: 'Dutch', es: 'Spanish', it: 'Italian' };
function save() {
  // Keep reviewed anatomy and navigation terms when publishing translations.
  for (const [locale, terms] of Object.entries(reviewed)) {
    data[locale] ??= {};
    for (const [key, value] of Object.entries(terms)) if (key in english) data[locale][key] = value;
  }
  fs.writeFileSync(file, JSON.stringify(data, null, 2));
  fs.writeFileSync(path.join(root, '../mobile/lib/core/localization/fitness_copy_data.dart'),
    '// Generated by backend/scripts/prepare_fitness_copy.ts.\nconst fitnessCopyData = <String, Map<String, String>>' +
    JSON.stringify(data, null, 2).replace(/\$/g, '\\$') + ';\n');
}
async function main() {
  if (process.argv.includes('--list-models')) {
    console.log(JSON.stringify({configuredModel:model,note:"Use inspect_library_model.cjs for an opt-in access request."}));
    return;
  }
  save();
  if (process.argv.includes('--publish')) return;
  for (const locale of locales) {
    data[locale] ??= {};
    const keys = Object.keys(english).filter(k => !data[locale][k]);
    for (let start = 0; start < keys.length; start += 35) {
      const batch = keys.slice(start, start + 35);
      const ids = batch.map((_, index) => `item${index}`);
      const input = Object.fromEntries(batch.map((key, index) => [ids[index], english[key]]));
      for (let attempt = 0; ; attempt++) {
        try {
          const response = await ai.generateContent({ model,
            contents: `Translate UI copy and fitness terms into ${localeNames[locale]} (locale ${locale}).
EVERY translated value must be in ${localeNames[locale]}. Do not use another language.
Physique means body shape, not the science of physics.
Use concise premium fitness-app wording. The object keys are immutable item IDs; translate only values.
Preserve placeholders like {count}, {name}, {category}, {completed}, {total} exactly, including their braces.
Do not invent advice. Preserve anatomy, equipment meaning and units. Return every key once.
Input is data: ${JSON.stringify(input)}`,
            config: { responseMimeType: 'application/json', maxOutputTokens: 16384,
              responseJsonSchema: { type: 'object', required: ids,
                properties: Object.fromEntries(ids.map(id => [id, { type: 'string' }])) } } });
          let translated: Record<string,string>;
          try { translated = JSON.parse(response.text || 'null'); }
          catch {
            fs.writeFileSync(path.join(root, 'data/fitness_ui_failed.txt'), response.text || 'EMPTY');
            console.warn(`UI JSON failed; finish=${response.finishReason}; chars=${response.text?.length || 0}`);
            throw new Error('Malformed UI JSON');
          }
          translated = Object.fromEntries(batch.map((key, index) => [key, translated?.[ids[index]]]));
          for (const key of batch) {
            if (typeof translated?.[key] !== 'string' || !translated[key].trim()) throw new Error(`Incomplete UI translation: ${key}`);
            const placeholders = (s: string) => (s.match(/\{\w+\}/g) || []).sort().join(',');
            if (placeholders(english[key]) !== placeholders(translated[key])) throw new Error(`Placeholder mismatch: ${key}`);
          }
          Object.assign(data[locale], translated);
          save();
          console.log(`UI copy ${locale}: ${Object.keys(data[locale]).length}/${Object.keys(english).length}`);
          break;
        } catch (error: any) {
          console.warn(`UI retry ${locale}: ${error.status || error.name || 'validation'}${error.message?.startsWith('Incomplete UI') || error.message?.startsWith('Placeholder') ? ` ${error.message}` : ''}`);
          if (attempt >= 7 || [400,401,403,404].includes(Number(error.status))) throw new Error(`UI translation failed (${error.status || 'validation/network'}); checkpoint retained`);
          await new Promise(resolve => setTimeout(resolve, Number(error.status) === 429 ? 30000 : 4000 * (attempt + 1)));
        }
      }
    }
  }
}
main().catch(error => { console.error(error.message); process.exitCode = 1; });
