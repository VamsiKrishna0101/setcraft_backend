// Import literal SVG geometry only; never execute downloaded JavaScript.
import fs from "node:fs";
import path from "node:path";

async function main() {
  const base = "https://raw.githubusercontent.com/HichamELBSI/react-native-body-highlighter/main/";
  const names = ["bodyFront", "bodyBack", "bodyFemaleFront", "bodyFemaleBack"];
  const keys = ["male_front", "male_back", "female_front", "female_back"];
  const models: Record<string, Record<string, string[]>> = {};
  const localSource = process.argv[2];
  async function readSource(file: string) {
    if (localSource) return fs.readFileSync(path.join(localSource, file), "utf8");
    const response = await fetch(base + (file === "LICENSE" ? file : "assets/" + file));
    if (!response.ok) throw new Error(`Anatomy download failed: ${response.status}`);
    return response.text();
  }
  for (let i = 0; i < names.length; i++) {
    const source = await readSource(`${names[i]}.ts`);
    const match = source.match(/=\s*(\[[\s\S]*\]);?\s*$/);
    if (!match) throw new Error("Anatomy literal not found");
    // These upstream files contain double-quoted strings and plain object keys.
    // JSON.parse rejects expressions; downloaded code is never evaluated.
    const json = match[1].replace(/^\s*\/\/.*$/gm, "")
      .replace(/([,{]\s*)([a-zA-Z][\w-]*)(\s*:)/g, '$1"$2"$3')
      .replace(/,\s*([}\]])/g, "$1");
    const entries = JSON.parse(json) as Array<{ slug: string; path: Record<string, string[]> }>;
    if (!Array.isArray(entries) || entries.some(entry => typeof entry.slug !== "string" || Object.values(entry.path).some(paths => !Array.isArray(paths) || paths.some(p => typeof p !== "string")))) throw new Error("Invalid anatomy geometry");
    models[keys[i]] = Object.fromEntries(entries.map(entry => [entry.slug, Object.values(entry.path).flat()]));
    console.log(`${keys[i]}: ${entries.length} anatomical groups`);
  }
  const target = path.resolve("../mobile/lib/features/body_scan/views/widgets/anatomy_path_data.dart");
  const lines = ["// SVG geometry adapted from react-native-body-highlighter.", "// Copyright (c) 2022 ELABBASSI Hicham. MIT; see assets/anatomy/LICENSE.", "// Generated by backend/scripts/import_anatomy_assets.ts; source contains literal paths only.",
    "const anatomyPathData = <String, Map<String, List<String>>>{"];
  for (const [model, groups] of Object.entries(models)) {
    lines.push(`  '${model}': {`);
    for (const [slug, paths] of Object.entries(groups)) lines.push(`    '${slug}': [${paths.map(p => JSON.stringify(p)).join(",")}],`);
    lines.push("  },");
  }
  lines.push("};"); fs.writeFileSync(target, lines.join("\n"));
  const license = await readSource("LICENSE");
  fs.mkdirSync("../mobile/assets/anatomy", { recursive: true });
  fs.writeFileSync("../mobile/assets/anatomy/LICENSE", license);
  fs.writeFileSync("../mobile/assets/anatomy/README.md", "Vector geometry from https://github.com/HichamELBSI/react-native-body-highlighter (MIT, ELABBASSI Hicham). Imported 6 October 2026. Used as an anatomical training guide; it is not measured user anatomy. Primary muscle data and UI are implemented separately in FitAI.\n");
}
main().catch(error => { console.error(error); process.exitCode = 1; });
